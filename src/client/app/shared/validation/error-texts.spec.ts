/**
 * Юнит-тесты словаря текстов ошибок полей (FR-023, контракт IF-010).
 *
 * Словарь — единственный источник текстов для UI, поэтому тексты
 * проверяются ДОСЛОВНО по FR-023 (§8 спеки 3.2): toEqual по полному
 * объекту ловит и отсутствие ключа, и любую правку литерала. Тексты из
 * внешних дизайн-артефактов («Введите целое число больше 0», «Не более
 * 500 символов», «Введите логин») в словарь не входят — фиксируется
 * отсутствием лишних ключей (toEqual строгое по ключам).
 */
import { ERROR_TEXTS } from './error-texts';

describe('Словарь ERROR_TEXTS (FR-023, IF-010)', () => {
  it('дословно совпадает со словарём FR-023 — все 17 текстов', () => {
    expect(ERROR_TEXTS).toEqual({
      required: 'Заполните поле',
      'password.min': 'Пароль должен содержать не менее 8 символов',
      'password.digit': 'Пароль должен содержать хотя бы одну цифру',
      'password.letter': 'Пароль должен содержать хотя бы одну букву',
      'password.special': 'Пароль должен содержать хотя бы один специальный знак',
      'password.mismatch': 'Пароли не совпадают',
      email: 'Введите корректный email',
      'email.length': 'Email — не более 254 символов',
      login: 'Логин — от 1 до 100 символов',
      'login.charset':
        'Логин может содержать только латинские буквы, цифры, точку, дефис и подчёркивание',
      code: 'Код должен состоять из 6 цифр',
      'lab.number': 'Номер должен быть положительным числом',
      'lab.semester': 'Семестр — число от 1 до 10',
      'lab.content': 'Содержание — от 1 до 500 символов',
      'lab.url': 'Ссылка должна начинаться с http:// или https://',
      'group.name': 'Название группы — от 1 до 100 символов',
      fullName: 'ФИО — от 1 до 200 символов',
    });
  });

  it('тексты дизайн-артефактов, отличные от словаря, не применяются — лишних ключей нет', () => {
    const keys = Object.keys(ERROR_TEXTS);
    expect(keys.length).toBe(17);
    expect(keys).not.toContain('number.int');
    expect(keys).not.toContain('content.max');
    expect(keys).not.toContain('login.required');
  });

  it('тип-литералы: значения не пустые, без крайних пробелов', () => {
    for (const text of Object.values(ERROR_TEXTS)) {
      expect(text.length).toBeGreaterThan(0);
      expect(text).toBe(text.trim());
    }
  });
});
