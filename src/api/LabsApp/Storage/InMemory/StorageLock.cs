namespace LabsApp.Storage.InMemory;

/// <summary>
/// Единая блокировка всего in-memory хранилища (ADR-002): все операции всех
/// репозиториев выполняются под одним объектом, поэтому межрепозиторные каскады
/// (удаление группы → сброс GroupId, удаление работы → удаление сдач) атомарны
/// так же, как и одиночные операции. DI-singleton; инжектируется конструкторам
/// реализаций. При переходе на PostgreSQL замещается ограничениями БД.
/// </summary>
public sealed class StorageLock
{
    /// <summary>Объект блокировки; доступен только реализациям хранилища (сборка LabsApp).</summary>
    internal object SyncRoot { get; } = new();
}
