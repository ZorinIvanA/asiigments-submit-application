namespace LabsApp.Auth;

/// <summary>
/// KDF-сервис паролей (IF-002, FR-005): PBKDF2-HMAC-SHA256
/// (Rfc2898DeriveBytes), соль 16 байт CSPRNG, ключ 32 байта, число итераций
/// новых хэшей — Auth__Pbkdf2Iterations. Формат хранимой строки:
/// «pbkdf2-sha256$&lt;iterations&gt;$&lt;saltBase64&gt;$&lt;hashBase64&gt;».
/// Verify читает параметры из САМОГО хэша (смена конфигурации не ломает старые
/// хэши); malformed-хэш → false БЕЗ деривации и без инкремента счётчика.
/// VerifyReference — эталонная ветка равной стоимости (AR-004): ровно одна
/// деривация против эталонного хэша, созданного при старте с текущими
/// параметрами; результат всегда отбрасывается. КАЖДАЯ деривация инкрементирует
/// <see cref="IKdfCounter"/> с меткой вызывателя (<see cref="KdfCallers"/>).
/// Коды восстановления хэшируются НЕ здесь (быстрый солёный SHA-256 в
/// ITokenService — ASM-005). Потребители: контроллеры auth (C-005/C-006/C-010),
/// сид (C-003). Пароли/хэши не логируются (NFR-006).
/// </summary>
public interface IPasswordHasher
{
    /// <summary>
    /// Хэширует пароль: свежая соль 16 байт CSPRNG, итерации текущей
    /// конфигурации, ровно одна деривация (инкремент счётчика с меткой caller).
    /// </summary>
    string Hash(string password, string caller);

    /// <summary>
    /// Проверяет пароль против хранимой строки: параметры (алгоритм, итерации,
    /// соль) читаются из самого хэша; ровно одна деривация (инкремент с меткой
    /// caller); сравнение — постоянное время. Malformed-хэш или пароль длиннее
    /// 128 символов (ASM-015) → false НЕМЕДЛЕННО, без KDF и без инкремента.
    /// </summary>
    bool Verify(string password, string storedHash, string caller);

    /// <summary>
    /// Эталонная проверка (ветка неизвестного логина, FR-007): ровно одна
    /// деривация против эталонного хэша, созданного при старте с текущими
    /// параметрами (метка reference); результат ВСЕГДА отбрасывается
    /// вызывающим. Пароль длиннее 128 символов → false без деривации.
    /// </summary>
    bool VerifyReference(string password);
}
